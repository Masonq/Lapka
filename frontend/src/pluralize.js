/**
 * Русское склонение существительных по числу: pluralize(1, ["потеряшка","потеряшки","потеряшек"]) -> "потеряшка"
 * Стандартное правило: последняя цифра 1 (кроме 11) -> форма 1; 2-4 (кроме 12-14) -> форма 2; иначе -> форма 3
 */
export function pluralize(n, [one, few, many]) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}
